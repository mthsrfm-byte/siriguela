import json, os
ROOT = os.path.join(os.path.dirname(__file__), "..", "theme", "locales")

def nest(flat):
    out = {}
    for k, v in flat.items():
        cur = out
        parts = k.split(".")
        for p in parts[:-1]:
            cur = cur.setdefault(p, {})
        cur[parts[-1]] = v
    return out

